def _all(family=None):
    """
    family 的三种语义，必须分清，否则默认页会变成一锅乱炖：
      None / "" / "common" → 只给通用坑（用户还没说岗位时，别拿别的岗位的坑吓他）
      "all"                → 全部（后台或检索用）
      具体岗位族 key        → 该族 + 通用（通用坑对所有人都成立，必须带上）
    """
    if family in (None, "", "common"):
        return [dict(x, scope="所有岗位通用", family="common") for x in COMMON]
    if family == "all":
        out = []
        for k in FAMILY:
            out += [dict(x, scope=fam_label(k), family=k) for x in FAMILY[k]]
        out += [dict(x, scope="所有岗位通用", family="common") for x in COMMON]
        return out
    out = [dict(x, scope=fam_label(family), family=family) for x in FAMILY.get(family, [])]
    out += [dict(x, scope="所有岗位通用", family="common") for x in COMMON]
    return out


def fam_label(family):
    from . import industry
    return (industry.FAMILIES.get(family) or industry.GENERIC)["label"]


def list_for(family=None, keyword="", stage=""):
    """
    family: 岗位族 key；keyword: 全文检索；stage: 阶段筛选。
    family 给了就返回「该岗位族 + 通用」，因为通用坑对所有人成立。
    """
    items = _all(family)
    if stage:
        items = [x for x in items if x["stage"] == stage]
    kw = (keyword or "").strip().lower()
    if kw:
        def hit(x):
            blob = " ".join(str(x.get(k, "")) for k in
                            ("title", "scene", "signal", "avoid", "fix", "write", "scope")).lower()
            return all(w in blob for w in re.split(r"\s+", kw) if w)
        items = [x for x in items if hit(x)]
    # 高严重性 + 岗位专用 优先
    sev = {"高": 0, "中": 1, "低": 2}
    items.sort(key=lambda x: (0 if x.get("family") == family and family else 1,
                              sev.get(x["severity"], 3)))
    return items


