def merge(industry_module):
    """把增量并进 industry 模块。必须在 industry.py 定义完函数之后调用。"""
    for k, f in EXTRA_FAMILIES.items():
        industry_module.FAMILIES.setdefault(k, f)
    for k in EXTRA_ORDER:
        if k not in industry_module.FAMILY_ORDER:
            industry_module.FAMILY_ORDER.append(k)
    for k, words in ALIAS_ADD.items():
        fam = industry_module.FAMILIES.get(k)
        if not fam:
            continue
        cur = fam.setdefault("aliases", [])
        for w in words:
            if w not in cur:
                cur.append(w)
