def audit(text, family="generic"):
    """
    对一段简历文字做「会被问穿」的检测。
    返回风险列表 + 该岗位族的细节题（probes）。

    注意：这是启发式。输出里必须保留 `note`，提醒用户这是提示而非判定。
    """
    text = text or ""
    risks = []
    for r in OVERREACH_RULES:
        if re.search(r["re"], text):
            if r.get("ctx") and not re.search(r["ctx"], text):
                continue
            risks.append({
                "id": r["id"],
                "problem": r["problem"],
                "why": r["why"],
                "fix": r["fix"],
                "quote": _quote(text, r["re"]),
            })
    fam = FAMILIES.get(family) or GENERIC
    return {
        "family": family,
        "familyLabel": fam["label"],
        "risks": risks,
        "riskCount": len(risks),
        "probes": [{"q": p[0], "expect": p[1], "why": p[2]} for p in fam["probes"]],
        "note": "以上是规则给出的「高风险表述」，不是判定你在造假。"
                "如果这些事你真做了，把缺的细节补上即可；如果没做过，建议改成你真正做的部分。",
    }


def _quote(text, pattern, width=16):
    m = re.search(pattern, text)
    if not m:
        return ""
    s = max(0, m.start() - width)
    e = min(len(text), m.end() + width)
    return ("…" if s else "") + text[s:e] + ("…" if e < len(text) else "")


