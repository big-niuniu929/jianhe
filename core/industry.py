VOCAB_INDEX = None


def _index():
    global VOCAB_INDEX
    if VOCAB_INDEX is None:
        VOCAB_INDEX = []
        for key, fam in FAMILIES.items():
            for v in fam["vocab"]:
                VOCAB_INDEX.append({
                    "family": key, "familyLabel": fam["label"],
                    "w": v[0], "def": v[1], "why": v[2], "use": v[3], "trap": v[4],
                })
    return VOCAB_INDEX


def _word_cands(w):
    """
    把一个词条拆成「可以拿去文本里搜」的候选串。
    难点：词条里既有 "A/B 测试" 这种不可拆的，也有 "SKU / SPU" 这种该拆的。
    规则：
      - 去掉括号补充说明；
      - 形如 "A/B 测试"（单字母 + 斜杠开头）的不拆，整体匹配；
      - 其余按斜杠拆，但每一段至少 3 个字符才留（避免 "A"、"B" 这种噪声）。
    """
    base = re.sub(r"[（(][^）)]*[）)]", "", w or "").strip()
    if not base:
        return []
    out = [base]
    if "/" in base or "／" in base:
        if re.match(r"^[A-Za-z]\s*[／/]", base):
            return out  # A/B 测试：整词匹配
        for part in re.split(r"[／/]", base):
            part = part.strip()
            if len(part) >= 3:
                out.append(part)
    # 去掉空格再补一个候选，兼容 "SKU/SPU" 与 "SKU / SPU" 两种写法
    nospace = re.sub(r"\s+", "", base)
    if nospace and nospace != base:
        out.append(nospace)
    return [x for x in out if len(x) >= 2]


def find_vocab(text):
    """
    从任意文本里抓出属于本知识库的专业词，附释义。
    这是「临时抱佛脚」最直接的用法：把 JD 粘进来，把不认识的词挑出来。
    """
    low = (text or "").lower()
    nospace = re.sub(r"\s+", "", low)
    out, seen = [], set()
    for item in _index():
        for cand in _word_cands(item["w"]):
            key = cand.lower()
            if key in seen:
                continue
            if key in low or re.sub(r"\s+", "", key) in nospace:
                seen.add(key)
                out.append(dict(item, matched=cand))
                break
    return out


