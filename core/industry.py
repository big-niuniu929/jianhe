def analyze(role="", jd="", profile=None):
    """
    生成岗位分析卡。纯规则，不依赖大模型，所以离线/断网也能用。
    角色识别优先用 role，其次从 JD 里推。
    """
    src = (role or "") + " " + (jd or "")
    key, conf, hits = detect(src)
    fam = FAMILIES.get(key) or GENERIC

    # 从 JD 里捞出这个岗位族的高频词，用于「你必须会的词」排序
    jd_vocab = find_vocab(jd) if jd else []
    jd_words = {v["matched"] for v in jd_vocab}

    vocab = []
    jd_low = (jd or "").lower()
    for v in fam["vocab"]:
        vocab.append({
            "w": v[0], "def": v[1], "why": v[2], "use": v[3], "trap": v[4],
            "inJd": any(c.lower() in jd_low for c in _word_cands(v[0])) if jd_low else False,
        })
    # JD 里出现的排前面
    vocab.sort(key=lambda x: (not x["inJd"],))

    return {
        "ok": True,
        "family": key,
        "familyLabel": fam["label"],
        "confidence": round(conf, 2),
        "matchedBy": hits[:6],
        "oneLiner": fam["one_liner"],
        "reportTo": fam["report_to"],
        "kpi": fam["kpi"],
        "rhythm": [{"when": k, "what": v} for k, v in fam["rhythm"].items()],
        "industry": fam["industry"],
        "org": fam["org"],
        "vocab": vocab,
        "levels": [{"tier": t[0], "ok": t[1], "notOk": t[2]} for t in fam["levels"]],
        "probes": [{"q": p[0], "expect": p[1], "why": p[2]} for p in fam["probes"]],
        "tools": fam["tools"],
        "jdVocab": jd_vocab,
        "mode": "rules",
        "source": "内置岗位知识库（%d 个岗位族 / %d 个词条）" % (
            len(FAMILIES), sum(len(f["vocab"]) for f in FAMILIES.values())),
    }


def families():
    """
    给前端做岗位选择器。

    只列内置族。模型补出来的族键名一律以 `x_` 开头（见 jobmap.py），
    这里过滤掉——不然用户下拉框里会慢慢长出一堆来源不明、质量不稳的条目，
    而选择器的作用恰恰是"告诉用户我们认真做过哪些岗位"。
    """
    return [{"key": k, "label": FAMILIES[k]["label"],
             "aliases": FAMILIES[k]["aliases"][:4]}
            for k in FAMILY_ORDER if not k.startswith("x_")]


def register(key, fam):
    """
    运行时挂一个岗位族进来（模型补齐的地图外岗位）。
    挂进 FAMILIES 而不是另起一个字典，是为了让 detect / analyze / audit
    三处都不用改——它们本来就只认 FAMILIES。
    """
    if key in FAMILIES:
        return False
    FAMILIES[key] = fam
    if key not in FAMILY_ORDER:
        FAMILY_ORDER.append(key)
    return True


def has(key):
    return key in FAMILIES


