# ---------------------------------------------------------------- 岗位族识别
def detect(role_text=""):
    """
    按别名命中打分。返回 (family_key, confidence, hits)。

    打分规则：得分 = Σ 别名长度 × (首位别名权重 2，其余 1)。
    为什么首位加权：每个族的 aliases[0] 是canonical 名（「后端」「销售」「新媒体」），
    它单独出现也足以定性；而「运营」这种泛词必须靠别的词一起才可信。
    为什么阈值取 2：中文岗位名常常只有两个字（后端 / 招聘 / 销售），
    阈值设 4 会让这些最该被识别的岗位全部落到 generic。
    """
    low = (role_text or "").lower()
    if not low.strip():
        return "generic", 0.0, []

    best, best_score, best_hits = "generic", 0.0, []
    for key in FAMILY_ORDER:
        fam = FAMILIES[key]
        hits, score = [], 0.0
        for i, a in enumerate(fam["aliases"]):
            al = a.lower()
            if al and al in low:
                hits.append(a)
                score += len(al) * (2 if i == 0 else 1)
        if score > best_score:
            best, best_score, best_hits = key, score, hits

    if best_score < 2:
        return "generic", 0.0, best_hits
    return best, min(1.0, best_score / 12.0), best_hits


