# -*- coding: utf-8 -*-
"""
generate_questions —— 面试防守清单
==================================
简历生成完只是上半场。下半场是"你写的每一句都会被追问"。
这里基于档案 + JD 缺口生成 8-12 个高概率追问，每题给：
考察点 / 回答框架（STAR 骨架）/ 常见坑 / 你的证据现状
规则来源：数字必问口径、角色边界、失败复盘、能力迁移、JD 缺口、时间线冲突。
"""
import re

from . import lexicon as LX
from .profile import iter_bullets


def generate(profile, jd_text="", jd_missing=None, limit=12):
    qs = []

    def add(q, kind, point, frame, trap, bid=None):
        qs.append({"q": q, "kind": kind, "point": point, "frame": frame, "trap": trap, "bulletId": bid})

    bullets = [(bid, title, b) for bid, sect, title, b in iter_bullets(profile)]

    # 1. 每个数字 → 口径追问（最高优先级）
    #    只挑「有业务含义」的数字，最多 3 条，避免整页都在问口径
    STRONG_UNIT = ("份", "人", "%", "％", "倍", "元", "台", "套", "条", "次", "小时", "分钟", "天", "SKU", "sku")
    num_q = 0
    for bid, title, b in bullets:
        if num_q >= 3:
            break
        t = b.get("text", "")
        nums = [x for tup in LX.QUANT_RE.findall(t) for x in tup if x]
        nums = [x for x in nums if any(u in x for u in STRONG_UNIT)]
        if not nums:
            continue
        n = nums[0]
        num_q += 1
        add(f"你写的「{n}」是怎么统计的？统计周期多长、样本有多少？",
            "数字口径", "考察数字是不是自己算的", 
            "S：场景（哪个业务口径）→ T：为什么需要这个数 → A：你怎么采集与清洗 → R：这个数说明了什么",
            "答不上统计周期，或者改口说「大概」——直接判定注水", bid)
        if not (b.get("evidence") or "").strip():
            add(f"这个「{n}」你现在还能拿出原始记录吗？（后台截图 / 台账 / 报表）",
                "证据核验", "考察真实性", "能当场提供更好；不能则说明数据来源与可复核方式",
                "说「在上一家公司电脑里」= 等于没有证据", bid)

    # 2. 角色边界（针对含"主导/独立/牵头"的 bullet）
    for bid, title, b in bullets:
        t = b.get("text", "")
        if any(w in t for w in ("主导", "独立", "牵头", "统筹", "从0到1", "0-1", "自研", "发起", "搭建")):
            add(f"「{title}」这件事里，哪些是你决定的、哪些是执行别人的决定？团队几个人？",
                "角色边界", "考察是否夸大个人贡献",
                "S：项目背景 → T：你被分到的目标 → A：你的决策点（举 1 个具体决策）→ R：结果与你的贡献占比",
                "把团队成果说成个人成果，一追问分工就露馅", bid)
            break

    # 3. 失败复盘（必须有）
    add("讲一个你做过但结果不好的事，你当时判断错在哪？",
        "失败复盘", "考察反思深度与诚实度",
        "S：目标 → T：你的假设 → A：实际发生了什么 → R：如果重来你改哪一步",
        "答「没有失败过」，或者把失败归因于别人/环境")

    # 4. 能力迁移（针对跨行业/跨岗位投递）
    roles = profile["intent"].get("targetRoles") or []
    if roles:
        add(f"你之前的经历和目标岗位「{roles[0]}」不完全一样，你怎么证明自己能上手？",
            "能力迁移", "考察自我认知与学习路径",
            "找一个可迁移的内核（数据分析/用户理解/项目推进）→ 举一个已经迁移成功的例子 → 说清还缺什么、怎么补",
            "只说「我学习能力强」，没有证据")

    # 5. JD 缺口
    for m in (jd_missing or [])[:2]:
        word = m.get("word") if isinstance(m, dict) else str(m)
        add(f"JD 里要求「{word}」，你哪里有相关经验？如果没做过，你打算怎么补？",
            "JD 缺口", "考察诚实度与准备度",
            "有就举最小可行的一次实践；没有就直说，并给出 2 周内的补法（课程/小项目/请教谁）",
            "硬编一个没做过的项目，第二个追问就崩")

    # 6. JD 隐性信号
    from .jd import extract_signals
    for s in extract_signals(jd_text)[:2]:
        add(f"（JD 隐含「{s['word']}」）请举一个体现「{s['word']}」的具体例子。",
            "隐性信号", s["why"], "STAR + 一个具体到时间地点的细节",
            "讲价值观、讲态度，不讲具体事件")

    # 7. 动机 / 协作 / 时间管理 / 短板（通用但高概率，保证题量到 8-12 题）
    role0 = (roles[0] if roles else "这个岗位")
    add(f"你为什么想做「{role0}」？做过什么来验证这个选择（不是兴趣，是动作）？",
        "岗位动机", "考察动机是否真实、有没有做过功课",
        "讲一次具体触发（做过什么、看到什么结果）→ 因此决定往这个方向 → 已经做了哪些准备",
        "只讲「感兴趣」「有热情」，没有任何行动证据")
    add("有没有一次你和同伴/同事意见不合，最后是怎么推进的？",
        "团队协作", "考察冲突处理与说服能力",
        "S：分歧是什么 → A：你怎么找共识（数据/试点/让步）→ R：最后的结果与关系",
        "把对方说成不讲理，或者答「我们没冲突过」")
    add("实习、课程、项目撞在一起的时候，你怎么排优先级？举一次真实的取舍。",
        "时间管理", "考察多线程与交付稳定性",
        "说清排序标准（截止/影响面/可替代性）→ 你放弃了什么 → 谁被告知、怎么补位",
        "答「我都能兼顾」，等于没回答")
    add("这份简历里，你自己最不自信的是哪一条？为什么？",
        "自我认知", "考察诚实度与改进意识",
        "挑一条真的弱的（例如无大厂实习）→ 说明客观限制 → 给出正在补的动作",
        "答「没有不自信的」，反而暴露没有反思")

    if profile["intent"].get("available"):
        add(f"你写的是「{profile['intent']['available']}」，学校这边能协调吗？如果临时加课怎么办？",
            "到岗承诺", "考察稳定性与兑现能力", "给出具体安排（课表/导师沟通/远程补位），不要空口承诺",
            "先答「没问题」，入职后频繁请假最伤口碑")

    # 8. 时间线 / 空白期
    add("从简历上看，你 XX 到 XX 这段时间在做什么？",
        "时间线", "考察是否有空白期与稳定性",
        "如实说明（备考/实习/项目），并说明这段时间的产出",
        "含糊带过，或与简历时间对不上")

    # 9. 反向问题（收尾加分项）
    add("你有什么想问我们的？（准备 2 个）",
        "反向提问", "考察你有多想来、有没有做功课",
        "问业务现状与岗位难点，不问薪资福利与「我能不能过」",
        "问「加班多吗」「什么时候出结果」")

    kind_prio = {"数字口径": 0, "证据核验": 1, "角色边界": 2, "JD 缺口": 3,
                 "失败复盘": 4, "能力迁移": 5, "隐性信号": 6, "岗位动机": 7,
                 "团队协作": 8, "时间管理": 9, "自我认知": 10, "到岗承诺": 11,
                 "时间线": 12, "反向提问": 13}
    qs.sort(key=lambda x: kind_prio.get(x["kind"], 8))
    return {"total": len(qs), "questions": qs[:limit]}
